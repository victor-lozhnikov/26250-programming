// гарантируется, что размер c = n + m
// гарантируется, что a и b отсортированы по неубыванию
// записать в c числа из a и b, чтобы c был отсортирован по неубыванию
void merge(int *a, int n, int *b, int m, int *c) {
    int i = 0;
    int j = 0;
    int k = 0;
    while((i<n) || (j<m)){
        if (i < n && (j == m || a[i] <= b[j])){
            c[k] = a[i];
            i++;
        }
        else {
            c[k] = b[j];
            j++;
        }
        k++;
    }
}
