// дан массив целых чисел из 2n - 1 эл-тов
// все числа от 1 до n
// все числа встречаются 2 раза, кроме одного
// найти уникальное число

// [1, 3, 5, 1, 4, 4, 3, 2, 2] -> 5

int find_unique(int n, int *a) {
    // a.size == 2 * n - 1
    int out = 0;
    for (int i = 0; i < 2*n-1; i++) {
        out ^= a[i];
    }
    return out;
}
