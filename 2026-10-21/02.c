// дан массив целых чисел из n + 1 эл-тов
// все числа от 1 до n
// все числа встречаются 1 раз, кроме одного, которое повторяется
// найти повторяющееся число

// [1, 2, 5, 3, 5, 4] -> 5

int find_not_unique(int n, int *a) {
    // a.size == n + 1
    int res = 0;
    for (int i=0; i<=n; i++){
        res ^= a[i];
    }
    for (int i=1; i<=n; i++){
        res ^= i;
    }
    return res;
}
